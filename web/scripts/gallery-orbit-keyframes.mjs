// 翻阅（flow）与环形（ring）的外部 CSS 关键帧与拖动投影共用 core/gallery-motion.ts 的同一个模型；prebuild 自动运行。
// 环形额外输出 --orbit-shade（0 = 正面，越往环后越大），由封面上的暗层读取，转到后面的封面变暗。
import {mkdtemp, readFile, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import ts from 'typescript';

const directory = await mkdtemp(join(tmpdir(), 'obi-orbit-css-'));
try {
  const source = await readFile(new URL('../src/core/gallery-motion.ts', import.meta.url), 'utf8');
  const result = ts.transpileModule(source, {compilerOptions: {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022}});
  const path = join(directory, 'gallery-motion.mjs');
  await writeFile(path, result.outputText);
  const {galleryOrbitPose} = await import(pathToFileURL(path).href);
  const number = value => String(Number(value.toFixed(7)));
  const scale = value => `calc(var(--gallery-size)*${number(value)})`;
  const rate = 2, frameCount = rate * 8;
  const block = mode => {
    const frames = Array.from({length: frameCount + 1}, (_, index) => {
      const pose = galleryOrbitPose(mode, index / rate - 4);
      const shade = mode === 'ring' ? `;--orbit-shade:${number(Math.min(.55, Math.max(0, (.16 - pose.z) / 2.8 * .55)))}` : '';
      return `  ${number(index * 100 / frameCount)}%{transform:translate(-50%,-50%) translate3d(${scale(pose.x)},${scale(pose.y)},${scale(pose.z)}) rotateX(${number(pose.rotateX)}deg) rotateY(${number(pose.rotateY)}deg) rotateZ(${number(pose.rotateZ)}deg) scale(${number(pose.scale)});opacity:${number(pose.opacity)}${shade}}`;
    });
    return [`.gallery-orbit.gallery-stage--${mode} .gallery-orbit-card{animation-name:gallery-orbit-${mode}}`, `@keyframes gallery-orbit-${mode}{`, ...frames, '}'];
  };
  await writeFile(new URL('../src/components/GalleryOrbit.css', import.meta.url), [
    '/* Generated by web/scripts/gallery-orbit-keyframes.mjs from core/gallery-motion.ts. */',
    '@property --orbit-shade{syntax:"<number>";inherits:true;initial-value:0}',
    ...block('flow'), ...block('ring'), '',
  ].join('\n'));
} finally {await rm(directory, {recursive: true, force: true});}
